"""Google Gemini API client for LLM Reasoning and Intent Extraction."""

from __future__ import annotations
import json
import urllib.request
import urllib.error
from typing import Optional, Dict, Any

from agent.llm.base import BaseLLMClient, LLMPlan
from agent.llm.rule_planner import RuleBasedPlanner


class GeminiLLMClient(BaseLLMClient):
    """Integrates Google Gemini models (Gemini 1.5 Flash, 2.0 Flash) with structured JSON output."""

    def __init__(self, api_key: str, model: str = "gemini-1.5-flash"):
        self.api_key = api_key
        self.model = model
        self.fallback = RuleBasedPlanner()

    def plan(
        self,
        user_input: str,
        conversation_history: str = "",
        last_draft: Optional[Dict[str, Any]] = None,
        contacts_summary: str = "",
    ) -> LLMPlan:
        if not self.api_key:
            return self.fallback.plan(user_input, conversation_history, last_draft, contacts_summary)

        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent?key={self.api_key}"

        system_prompt = (
            "You are the reasoning and planning module of an autonomous AI Agent.\n"
            "Analyze the user's latest message, recent conversation history, and memory state.\n"
            "Return a JSON object with this EXACT structure:\n"
            "{\n"
            '  "intent": "compose_email" | "confirm_send" | "reject_send" | "provide_contact" | "list_contacts" | "view_history" | "chat",\n'
            '  "recipient_name": string or null,\n'
            '  "recipient_email": string or null,\n'
            '  "subject": string or null,\n'
            '  "body": string or null,\n'
            '  "tone": "professional" | "casual" | "urgent" | "friendly" | "formal",\n'
            '  "reuse_context": boolean (true if user says "send the same email to X too" or references prior email),\n'
            '  "reasoning": string (concise explanation of your deduction)\n'
            "}\n\n"
            "CRITICAL RULES:\n"
            "1. If user confirms (yes, send, confirm, proceed, y), set intent='confirm_send'.\n"
            "2. If user cancels (no, stop, cancel, n), set intent='reject_send'.\n"
            "3. If user mentions 'send the same to X too', set reuse_context=true and recipient_name=X.\n"
            "4. NEVER hallucinate email addresses. Only set recipient_email if explicitly provided by the user in the prompt.\n"
        )

        user_prompt_content = (
            f"Known Contacts:\n{contacts_summary}\n\n"
            f"Recent Conversation History:\n{conversation_history}\n\n"
            f"Last Draft in Memory:\n{json.dumps(last_draft or {}, indent=2)}\n\n"
            f"User Input:\n{user_input}\n"
        )

        payload = {
            "contents": [
                {
                    "parts": [
                        {"text": system_prompt + "\n\n" + user_prompt_content}
                    ]
                }
            ],
            "generationConfig": {
                "responseMimeType": "application/json",
                "temperature": 0.2,
            },
        }

        try:
            req_data = json.dumps(payload).encode("utf-8")
            req = urllib.request.Request(
                url,
                data=req_data,
                headers={"Content-Type": "application/json"},
                method="POST",
            )
            with urllib.request.urlopen(req, timeout=10) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                candidate = data["candidates"][0]["content"]["parts"][0]["text"]
                parsed = json.loads(candidate)

                return LLMPlan(
                    intent=parsed.get("intent", "chat"),
                    recipient_name=parsed.get("recipient_name"),
                    recipient_email=parsed.get("recipient_email"),
                    subject=parsed.get("subject"),
                    body=parsed.get("body"),
                    tone=parsed.get("tone", "professional"),
                    reuse_context=bool(parsed.get("reuse_context", False)),
                    reasoning=parsed.get("reasoning", "Generated by Gemini LLM"),
                    raw_response=candidate,
                )
        except Exception:
            # On network timeout, rate limit, or sandbox restriction, seamlessly fall back to rule-based planner
            return self.fallback.plan(user_input, conversation_history, last_draft, contacts_summary)
